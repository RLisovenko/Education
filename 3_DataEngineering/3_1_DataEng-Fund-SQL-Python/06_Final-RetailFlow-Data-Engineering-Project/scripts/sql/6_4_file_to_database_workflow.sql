DROP TABLE IF EXISTS orders_items_raw;

CREATE TABLE orders_items_raw (
    order_id INTEGER,
    customer_id INTEGER,
    item_id INTEGER,
    quantity INTEGER,
    price NUMERIC(10,2),
    order_date DATE
);

ALTER TABLE orders_items_raw
ADD COLUMN error_reason VARCHAR(200);

-- Load CSV in psql from data/raw:
-- \copy orders_items_raw (order_id, customer_id, item_id, quantity, price, order_date) FROM 'in_order_316_customer_7.csv' DELIMITER ',' CSV HEADER;

SELECT * FROM orders_items_raw;

SELECT COUNT(*) AS loaded_rows
FROM orders_items_raw
WHERE order_id = 316
  AND customer_id = 7;

SELECT *
FROM orders_items_raw
WHERE order_id IS NULL
   OR customer_id IS NULL
   OR item_id IS NULL
   OR quantity IS NULL
   OR quantity <= 0
   OR price IS NULL
   OR price <= 0
   OR order_date IS NULL;

UPDATE orders_items_raw
SET error_reason = 'Missing item_id'
WHERE item_id IS NULL;

UPDATE orders_items_raw
SET quantity = NULL,
    error_reason = 'Missing quantity'
WHERE quantity <= 0;

UPDATE orders_items_raw
SET error_reason = 'Invalid price: ' || price::text,
    price = NULL
WHERE price <= 0;

SELECT
    order_id,
    item_id,
    COUNT(*) AS duplicate_count
FROM orders_items_raw
GROUP BY order_id, item_id
HAVING COUNT(*) > 1;

WITH duplicates AS (
    SELECT
        ctid,
        ROW_NUMBER() OVER (
            PARTITION BY order_id, item_id
            ORDER BY ctid
        ) AS rn
    FROM orders_items_raw
    WHERE item_id IS NOT NULL
)
UPDATE orders_items_raw r
SET error_reason =
    'Duplicate item_id: ' || r.item_id::text ||
    ', quantity: ' || COALESCE(r.quantity::text, 'NULL')
FROM duplicates d
WHERE r.ctid = d.ctid
  AND d.rn > 1;

SELECT * FROM orders_items_raw;

-- Configure automatic id generation in final table.
ALTER TABLE orders_items
ALTER COLUMN id
ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(
    pg_get_serial_sequence('orders_items', 'id'),
    (SELECT MAX(id) FROM orders_items),
    true
);

-- Prevent duplicate items inside the same order.
ALTER TABLE orders_items
ADD CONSTRAINT uq_order_item
UNIQUE (order_id, item_id);

-- Load only valid records.
INSERT INTO orders_items (
    order_id,
    item_id,
    quantity,
    price
)
SELECT
    r.order_id,
    r.item_id,
    r.quantity,
    r.price
FROM orders_items_raw r
WHERE r.error_reason IS NULL
ON CONFLICT (order_id, item_id) DO NOTHING;

SELECT *
FROM orders_items
ORDER BY order_id, item_id;

SELECT COUNT(*) AS final_order_316_rows
FROM orders_items
WHERE order_id = 316;

