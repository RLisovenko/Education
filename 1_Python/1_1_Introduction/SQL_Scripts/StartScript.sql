(id INTEGER PRIMARY KEY AUTOINCREMENT, &_
BL_id INTEGER , LK_id INTEGER, Stadt_id INTEGER, PLZ_id INTEGER, & _
Info TEXT NOT NULL, & _
Comment TEXT)

